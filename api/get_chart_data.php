<?php

/**
 * DetalStudio - Get Chart Data API
 * API для отримання даних графіків
 */

require_once __DIR__ . '/../config/config.php';

header('Content-Type: application/json');

Auth::requireAuth();

try {
    $months = isset($_GET['months']) ? (int)$_GET['months'] : 6;
    if ($months < 1 || $months > 24) $months = 6;

    // Get financial data
    $financials = Reports::getMonthlyFinancials($months);

    // Get completed tasks data (Optimized: Single Query)
    $startDate = date('Y-m-01', strtotime("-" . ($months - 1) . " months"));

    $stmt = db()->prepare("
        SELECT DATE_FORMAT(completed_at, '%Y-%m') as month_key, COUNT(*) as count 
        FROM tasks 
        WHERE status = 'completed' 
        AND completed_at >= ? 
        GROUP BY DATE_FORMAT(completed_at, '%Y-%m')
    ");
    $stmt->execute([$startDate]);
    $tasksResults = $stmt->fetchAll(PDO::FETCH_KEY_PAIR); // ['2023-10' => 5, '2023-11' => 8...]

    $tasksData = [];
    // Align with labels from financials which are generated by loop in Reports::getMonthlyFinancials
    // To match perfectly, we should ideally use the same loop for labels generation here or rely on financials['labels'] logic
    // But we need the data array to match the length and order of labels.

    // We can reconstruct the month keys to match the loop in Reports
    for ($i = $months - 1; $i >= 0; $i--) {
        $monthKey = date('Y-m', strtotime("-$i months"));
        $tasksData[] = (int)($tasksResults[$monthKey] ?? 0);
    }

    // Ensure numeric types are correct for JS
    $revenueData = array_map('floatval', $financials['income'] ?? []);
    $tasksData = array_map('intval', $tasksData);

    // 3. Manager Performance (Top 5)
    $managerRevenue = Reports::getManagerRevenue(5);

    // 4. Service Revenue Share (Top 5)
    $serviceRevenue = Reports::getServiceRevenueShare(5);

    // 5. Client Retention (Current Month)
    $clientStats = Reports::getClientRetention();

    echo json_encode([
        'labels' => $financials['labels'] ?? [],
        'revenue' => $revenueData,
        'tasks' => $tasksData,
        'managerRevenue' => $managerRevenue,
        'serviceRevenue' => $serviceRevenue,
        'clientStats' => $clientStats
    ]);
} catch (Exception $e) {
    error_log("get_chart_data API error: " . $e->getMessage());
    http_response_code(500);
    echo json_encode(['error' => 'Внутрішня помилка сервера']);
}
