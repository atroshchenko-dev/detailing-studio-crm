<script>
document.addEventListener('DOMContentLoaded', function() {
    // Configuration
    const config = {
        startHour: 8,
        endHour: 21, // 20:00 + 1 hour buffer
        hourWidth: 80, // pixels
    };
    
    let currentDate = new Date();
    let resources = [];
    let events = [];

    const els = {
        body: document.getElementById('timelineBody'),
        headerTrack: document.getElementById('timeHeaderTrack'),
        dateDisplay: document.getElementById('currentDateDisplay'),
        prevBtn: document.getElementById('prevDay'),
        nextBtn: document.getElementById('nextDay'),
        refreshBtn: document.getElementById('refreshBtn')
    };

    // Initialize
    initTimeline();

    function initTimeline() {
        renderHeader();
        fetchData();
        setupListeners();
    }

    function setupListeners() {
        els.prevBtn.addEventListener('click', () => changeDate(-1));
        els.nextBtn.addEventListener('click', () => changeDate(1));
        els.refreshBtn.addEventListener('click', fetchData);
    }

    function changeDate(days) {
        currentDate.setDate(currentDate.getDate() + days);
        fetchData();
    }

    function formatDate(date) {
        return date.toLocaleDateString('uk-UA', { weekday: 'short', day: 'numeric', month: 'long' });
    }

    function getISODate(date) {
        return date.toISOString().split('T')[0];
    }

    function renderHeader() {
        els.headerTrack.innerHTML = '';
        for (let h = config.startHour; h < config.endHour; h++) {
            const slot = document.createElement('div');
            slot.className = 'time-slot';
            slot.textContent = `${h.toString().padStart(2, '0')}:00`;
            els.headerTrack.appendChild(slot);
        }
        // Adjust width of tracks
        const totalWidth = (config.endHour - config.startHour) * config.hourWidth;
        els.headerTrack.style.width = `${totalWidth}px`;
    }

    async function fetchData() {
        els.dateDisplay.textContent = formatDate(currentDate);
        els.body.innerHTML = '<div class="text-center p-5 text-muted"><div class="spinner-border text-info mb-2"></div><div>Оновлення...</div></div>';

        const isoDate = getISODate(currentDate);
        
        try {
            // Parallel fetch
            const [resResponse, evResponse] = await Promise.all([
                fetch('/api/get_timeline_data.php?fetch=resources'),
                fetch(`/api/get_timeline_data.php?fetch=events&start=${isoDate}&end=${isoDate}`)
            ]);

            resources = await resResponse.json();
            events = await evResponse.json();

            renderTimeline();
        } catch (error) {
            console.error('Timeline error:', error);
            els.body.innerHTML = '<div class="text-center p-5 text-danger"><i class="bi bi-exclamation-triangle"></i> Помилка завантаження даних</div>';
        }
    }

    function renderTimeline() {
        els.body.innerHTML = '';
        
        // Calculate total width for tracks
        const totalWidth = (config.endHour - config.startHour) * config.hourWidth;

        resources.forEach(res => {
            const row = document.createElement('div');
            row.className = 'timeline-row';

            // Resource Name
            const resCell = document.createElement('div');
            resCell.className = 'resource-cell';
            resCell.textContent = res.title;
            row.appendChild(resCell);

            // Events Track
            const track = document.createElement('div');
            track.className = 'events-track';
            track.style.minWidth = `${totalWidth}px`; // Force width
            
            // Filter events for this resource
            const resEvents = events.filter(e => e.resourceId == res.id);
            
            resEvents.forEach(evt => {
                const el = createEventElement(evt);
                if (el) track.appendChild(el);
            });

            row.appendChild(track);
            els.body.appendChild(row);
        });

        // Add current time indicator if today
        if (getISODate(currentDate) === getISODate(new Date())) {
            addCurrentTimeIndicator();
        }
    }

    function createEventElement(evt) {
        // Parse dates
        const start = new Date(evt.start);
        const end = new Date(evt.end);

        // Timeline Bounds for today (Current Viewed Date)
        const year = currentDate.getFullYear();
        const month = currentDate.getMonth();
        const day = currentDate.getDate();

        // Visible timeline absolute bounds (ms)
        const timelineStartMs = new Date(year, month, day, config.startHour, 0, 0).getTime();
        const timelineEndMs = new Date(year, month, day, config.endHour, 0, 0).getTime();

        const evtStartMs = start.getTime();
        const evtEndMs = end.getTime();

        // Check intersection
        if (evtEndMs <= timelineStartMs || evtStartMs >= timelineEndMs) return null;

        // Clamp to visible area
        const visibleStartMs = Math.max(evtStartMs, timelineStartMs);
        const visibleEndMs = Math.min(evtEndMs, timelineEndMs);

        // Calculate dimensions in Hours
        // 1 Hour = 3600000 ms
        const offsetMs = visibleStartMs - timelineStartMs;
        const durationMs = visibleEndMs - visibleStartMs;

        const offsetHours = offsetMs / 3600000;
        const durationHours = durationMs / 3600000;

        const left = offsetHours * config.hourWidth;
        const width = durationHours * config.hourWidth;

        const el = document.createElement('a');
        el.className = 'event-item';
        el.dataset.id = evt.id; // For Drag & Drop
        el.href = evt.url || '#';
        el.style.left = `${left}px`;
        el.style.width = `${width}px`;
        el.style.backgroundColor = evt.backgroundColor || '#3788d8';
        el.style.borderColor = evt.borderColor || '#3788d8'; // Use border color if set

        // Content
        const title = document.createElement('div');
        title.className = 'event-title';
        title.textContent = evt.title;
        el.appendChild(title);

        if (evt.extendedProps && evt.extendedProps.car) {
            const sub = document.createElement('div');
            sub.className = 'event-subtitle';
            sub.textContent = evt.extendedProps.car;
            el.appendChild(sub);
        }

        return el;
    }

    function addCurrentTimeIndicator() {
        const now = new Date();
        const hourDec = now.getHours() + (now.getMinutes() / 60);
        
        if (hourDec < config.startHour || hourDec > config.endHour) return;

        const offset = (hourDec - config.startHour) * config.hourWidth;

        // We need to add this to EVERY row track, or overlay on top of body
        // Only visual on tracks? Let's add an absolute overlay to the body container implementation if we want lines across all.
        // For simplicity, let's just create one vertical line that overlays the whole body content?
        // Actually since body scrolls, it's tricky.
        // Easiest: Append a line to each row's track.
        
        document.querySelectorAll('.events-track').forEach(track => {
            const line = document.createElement('div');
            line.className = 'current-time-line';
            line.style.left = `${offset}px`;
            
            const head = document.createElement('div');
            head.className = 'current-time-head';
            line.appendChild(head);
            
            track.appendChild(line);
        });
    }

    // Auto refresh every 5 min
    const refreshInterval = setInterval(fetchData, 300000);

    // --- Drag and Drop Logic ---
    let dragItem = null;
    let dragStartX = 0;
    let dragOriginalLeft = 0;
    let dragData = null; // { event, originalStart, durationHours, resourceId }
    let isDragging = false;
    
    document.addEventListener('mousedown', function(e) {
        const item = e.target.closest('.event-item');
        if (!item) return;
        
        // Prevent drag on content click if we want to allow text selection? 
        // But here we want the whole block to move.
        // Prevent default primarily to avoid text selection cursor
        e.preventDefault();

        dragItem = item;
        dragStartX = e.clientX;
        dragOriginalLeft = parseFloat(item.style.left);
        
        // Disable transitions during drag for performance
        item.style.transition = 'none';
        item.style.zIndex = '1000';
        item.style.cursor = 'grabbing';
        
        // Find associated data
        // We need to attach data to element or look it up
        // Let's modify createEventElement to attach data ID
        const evtId = item.dataset.id;
        const evt = events.find(ev => ev.id == evtId);
        
        if (evt) {
            const start = new Date(evt.start);
            const end = new Date(evt.end);
            const durationMs = end - start;
            dragData = {
                id: evt.id,
                resourceId: evt.resourceId,
                startTime: start,
                durationMs: durationMs
            };
        }
        
        isDragging = true;
    });

    document.addEventListener('mousemove', function(e) {
        if (!isDragging || !dragItem) return;

        const deltaX = e.clientX - dragStartX;
        dragItem.style.left = `${dragOriginalLeft + deltaX}px`;
    });

    document.addEventListener('mouseup', function(e) {
        if (!isDragging || !dragItem) return;

        // Finalize
        const deltaX = e.clientX - dragStartX;
        const newLeft = dragOriginalLeft + deltaX;
        
        // Snap logic
        // 1 hour = config.hourWidth (80px)
        // 15 min = 20px
        const snapGrid = config.hourWidth / 4; 
        const snappedLeft = Math.round(newLeft / snapGrid) * snapGrid;
        
        // Re-apply style
        dragItem.style.transition = 'transform 0.1s, box-shadow 0.1s';
        dragItem.style.zIndex = '';
        dragItem.style.cursor = 'pointer';
        dragItem.style.left = `${snappedLeft}px`;
        
        // Calculate new time
        // left=0 is config.startHour
        const hoursOffset = snappedLeft / config.hourWidth;
        const newStartHourDec = config.startHour + hoursOffset;
        
        // Construct new date
        // Base is currentDate (only time changes, assuming handled within single day view for now)
        // But wait, currentDate is what we view. The event might be on a diff day if we viewed it?
        // No, we fetched events for this day.
        // Caution: If we dragged it far out of bounds?
        
        const newStartDate = new Date(currentDate);
        newStartDate.setHours(Math.floor(newStartHourDec));
        newStartDate.setMinutes((newStartHourDec % 1) * 60);
        newStartDate.setSeconds(0);
        
        const newEndDate = new Date(newStartDate.getTime() + dragData.durationMs);

        // TODO: Handle Vertical Drag (Changing Resources)
        // For now, only Horizontal.
        
        // Check bounds
        if (newStartDate.getHours() < config.startHour || newEndDate.getHours() > config.endHour + 1) {
            // Revert if wildly out of bounds (optional)
            // For now let backend handle or user fix.
        }

        updateEvent(dragData.id, newStartDate, newEndDate, dragData.resourceId);

        isDragging = false;
        dragItem = null;
        dragData = null;
    });

    function updateEvent(id, start, end, resourceId) {
        // Optimistic UI update already happened via style change
        
        // Format for MySQL
        const format = (d) => {
            // Adjust to local string YYYY-MM-DD HH:MM:SS
            // JS toISOString is UTC. We need local.
             const pad = (n) => n.toString().padStart(2, '0');
             return `${d.getFullYear()}-${pad(d.getMonth()+1)}-${pad(d.getDate())} ${pad(d.getHours())}:${pad(d.getMinutes())}:00`;
        };

        const formData = new FormData();
        formData.append('order_id', id);
        formData.append('start', format(start));
        formData.append('end', format(end));
        formData.append('stall_id', resourceId);

        fetch('/api/update_event_time.php', {
            method: 'POST',
            body: formData
        })
        .then(async r => {
            const res = await r.json();
            if (!r.ok || !res.success) {
                // Handle 409 Conflict or other errors
                alert('Помилка: ' + (res.message || 'Не вдалося оновити час'));
                fetchData(); // Revert to server state
            } else {
                // Success, could show a brief toast
            }
        })
        .catch(err => {
            console.error(err);
            alert('Помилка мережі при спробі оновлення');
            fetchData(); // Revert
        });
    }

});
</script>

